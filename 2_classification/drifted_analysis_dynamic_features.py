"""# Save classifier model
After the end of the classification process, we save the returned model. If it's Decision Tree or Random Forest, we save a .txt file with the tree(s), as well as a .pkl file with the classifier object. The latter can be later loaded with the `load_best_model_object()` method to do further analysis (if we want). The remainder of the algorithms are not easily interpretable, so there's no .txt file saved, only a .pkl.

The code below also differentiates between Random Forest and Decision Trees, as the former has a population of trees, and thus requires different treatment.
"""

def save_best_model(fname, clf):
  if str(clf).__contains__('RandomForestClassifier'):
    f = open(path + results + fname + '.txt', 'w')
    for i in range(len(clf.estimators_)):
      text_representation = tree.export_text(clf.estimators_[i], feature_names= features.tolist())
      with open(path + results + fname + '.txt', 'a') as output:
        output.write('Model ' + str(i) + '\n')
        output.write(text_representation)
        output.write('\n')

    with open(path + results + fname + '.pkl','wb') as f:
      pickle.dump(clf,f)
  elif str(clf).__contains__('DecisionTreeClassifier'):
    f = open(path + results + fname + '.txt', 'w')
    text_representation = tree.export_text(clf, feature_names= features.tolist())
    with open(path + results + fname + '.txt', 'w') as output:
      output.write(text_representation)

