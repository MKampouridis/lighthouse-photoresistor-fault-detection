"""# Machine Learning for classification
We use a single method for the classification purposes. The same pattern is followed for each method:

1.   Define hyperparameters' range for tuning
2.   Perform grid search (with cross-validation on the training set)
3.   Obtain best hyperparameter set and re-train
4.   Check performance on test set, and save results

This method takes a `classifier_obj` as an input parameter, which informs what classification algorithm is going to be used. The `params` argument informs the hyperparameters range (for the particular classification algorithm) for grid search hyperparameter tuning. The `dataset_name` informs what input (merged) dataset we are currently running.

Another thing to note here is that I am using the scaled values across all algorithms, even the tree-related ones (DT, RF, XGB) that don't require scaling. However, since their end result is not affected *at all* by scaling, I am using it there, too, for simplicity, so that I do not have to differentiate in the code for `X_train`/`X_test` and `X_train_scaled`/`X_test_scaled` for certain algorithms. (A reminder that the `y` variable doesn't require scaling, as it contains the target value).



"""


def learn(classifier_obj, params, dataset_name, X_train_scaled, X_test_scaled, y_train, y_test):
    clf = GridSearchCV(
        estimator=classifier_obj,
        param_grid=params,
        cv=kfolds,
        n_jobs=njobs
    )

    clf.fit(X_train_scaled, y_train)  # perform grid search

    clf2 = classifier_obj  # new classifer
    clf2.set_params(**clf.best_params_)  # set best estimator to the new classifier
    clf2.fit(X_train_scaled, y_train)  # train it
    predictions = clf2.predict(X_test_scaled)  # use best tree to make predictions in the test set
    # print('accuracy ', accuracy_score(y_test, predictions))

    classifier_name = (str(type(clf2).__name__)).split('(')[0]  # extracting the classifier's name from the object
    update_results(dataset_name, classifier_name, y_test, predictions)
    save_best_model(dataset_name + '/Best' + classifier_name + '-' + dataset_name, clf2)

    return clf2


